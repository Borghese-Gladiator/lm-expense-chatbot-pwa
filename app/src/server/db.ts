const SCHEMA_LOCK = 4711;

/** Rewrite `?` placeholders to `$1, $2, ...`. No SQL text in this app has a literal `?`. */
export function numbered(sql: string): string {
  let i = 0;
  return sql.replace(/\?/g, () => `$${++i}`);
}

export async function one<T = Row>(db: Db, sql: string, params?: unknown[]): Promise<T | undefined> {
  return (await db.query<T>(sql, params))[0];
}

export async function scalar<T = unknown>(db: Db, sql: string, params?: unknown[]): Promise<T> {
  const row = await one(db, sql, params);
  return (row ? Object.values(row)[0] : undefined) as T;
}

async function pgliteDb(dataDir?: string): Promise<Db> {
  const { PGlite, types } = await import("@electric-sql/pglite");
  if (dataDir) await mkdir(dataDir, { recursive: true });
  const pg = await PGlite.create({
    dataDir,
    parsers: { [types.DATE]: (v: string) => v, [types.NUMERIC]: Number, [types.INT8]: Number },
  });
  await pg.exec(SCHEMA);
  const wrap = (q: { query: typeof pg.query }): Db => ({
    async query<T>(sql: string, params: unknown[] = []) {
      return (await q.query<T>(numbered(sql), params)).rows;
    },
    tx: (fn) => pg.transaction((t) => fn(wrap(t))),
    close: () => pg.close(),
  });
  return wrap(pg);
}

async function postgresDb(directUrl: string, pooledUrl: string): Promise<Db> {
  const { default: pgLib } = await import("pg");
  pgLib.types.setTypeParser(1082, (v: string) => v);
  pgLib.types.setTypeParser(1700, (v: string) => Number(v));
  pgLib.types.setTypeParser(20, (v: string) => Number(v));
  const client = new pgLib.Client({ connectionString: directUrl });
  await client.connect();
  try {
    await client.query("SELECT pg_advisory_lock($1)", [SCHEMA_LOCK]);
    await client.query(SCHEMA);
    await client.query("SELECT pg_advisory_unlock($1)", [SCHEMA_LOCK]);
  } finally {
    await client.end();
  }
  const pool = new pgLib.Pool({ connectionString: pooledUrl || directUrl, max: 3 });
  type Queryable = { query: (sql: string, params: unknown[]) => Promise<{ rows: unknown[] }> };
  const run = async <T>(c: Queryable, sql: string, params: unknown[] = []) =>
    (await c.query(numbered(sql), params)).rows as T[];
  return {
    query: (sql, params) => run(pool, sql, params),
    async tx(fn) {
      const c = await pool.connect();
      const inTx: Db = {
        query: (sql, params) => run(c, sql, params),
        tx: (inner) => inner(inTx),
        close: async () => {},
      };
      try {
        await c.query("BEGIN");
        const out = await fn(inTx);
        await c.query("COMMIT");
        return out;
      } catch (e) {
        await c.query("ROLLBACK");
        throw e;
      } finally {
        c.release();
      }
    },
    close: () => pool.end(),
  };
}

export function openDb(
  settings: Pick<Settings, "databaseUrl" | "pgliteDir"> & Partial<Pick<Settings, "databaseUrlPooled">>,
  memory = false,
): Promise<Db> {
  if (memory) return pgliteDb();
  if (settings.databaseUrl) return postgresDb(settings.databaseUrl, settings.databaseUrlPooled ?? "");
  return pgliteDb(settings.pgliteDir);
}

export async function categoryIdFor(db: Db, name: string, group: string | null = null): Promise<number> {
  const existing = await scalar<number | undefined>(
    db,
    "SELECT id FROM categories WHERE lower(name) = lower(?)",
    [name],
  );
  if (existing !== undefined) return Number(existing);
  const lowered = `${name} ${group ?? ""}`.toLowerCase();
  let kind = "expense";
  if (lowered.includes("transfer") || lowered.includes("credit card payment")) kind = "transfer";
  else if (["income", "paycheck", "salary"].some((w) => lowered.includes(w))) kind = "income";
  return Number(
    await scalar(db, "INSERT INTO categories (name, group_name, kind) VALUES (?, ?, ?) RETURNING id", [
      name,
      group,
      kind,
    ]),
  );
}
